function validate_scene(c)
assert(c.scene.measurementsConfirmed,'Project:MeasurementsNeeded', ...
    '请先更新experiment_config.m的本轮测量，并将scene.measurementsConfirmed改为true。');
assert(c.scene.parallelPlanesConfirmed,'Project:ParallelPlanesNeeded', ...
    '当前论文入口要求屏幕和小片平行白板，请核实并设置parallelPlanesConfirmed。');
s=c.scene;
v=[s.screenWallDistanceCm s.screenSizeCm s.screenCenterXZCm ...
   s.occluderSizeCm s.occluderCenterXZCm s.occluderWallFacingDistanceCm s.occluderThicknessCm];
assert(all(isfinite(v)),'Project:GeometryFinite','测量参数有缺失或非有限数值。');
assert(s.screenWallDistanceCm>0 && all(s.screenSizeCm>0) && all(s.occluderSizeCm>0));
assert(s.occluderThicknessCm>=0 && s.occluderWallFacingDistanceCm>0 && ...
 s.occluderWallFacingDistanceCm+s.occluderThicknessCm<s.screenWallDistanceCm, ...
 'Project:DepthOrder','应满足0<小片到白板距离<屏幕到白板距离。');
assert(ismember(s.occluderPlane,{'wall_facing_surface','midplane'}));
assert(numel(c.wall.rectangleCm)==4 && all(isfinite(c.wall.rectangleCm)) && ...
 all(c.wall.rectangleCm(3:4)>0),'Project:WallRectangleNeeded', ...
 '请填写wall.rectangleCm=[白板采样区左下x 左下z 宽 高]。');
assert(isscalar(c.wall.gridSize) && c.wall.gridSize>=2 && mod(c.wall.gridSize,1)==0);
assert(numel(c.source.gridRowsCols)==2 && all(c.source.gridRowsCols>=2) && all(mod(c.source.gridRowsCols,1)==0));
assert(isscalar(c.transport.subsamplesPerAxis) && c.transport.subsamplesPerAxis>=2 && mod(c.transport.subsamplesPerAxis,1)==0, ...
 'Project:SourceSubsampling','原作者函数的此入口要求subsamplesPerAxis至少为2。');
if s.includeSupport
 assert(isfinite(s.supportCenterXCm) && s.supportDiameterCm>0 && ...
   all(isfinite(s.supportBottomTopZCm)) && diff(s.supportBottomTopZCm)>0);
end
end
